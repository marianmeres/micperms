/**
 * Writes the current package version into `example/dist/version.js` so both example
 * pages can display it without reading `deno.json` at runtime. Run as the first step
 * of the `build:example*` tasks, and therefore by the release `--before-commit` hook
 * (after the manifest bump, so it sees the new version).
 */
import { mkdir, writeFile } from "node:fs/promises";
import denoJson from "../deno.json" with { type: "json" };

const outDir = new URL("../example/dist/", import.meta.url);
const out = `// AUTO-GENERATED by scripts/gen-example-version.ts — do not edit.\n` +
	`export const VERSION = ${JSON.stringify(denoJson.version)};\n`;

await mkdir(outDir, { recursive: true });
await writeFile(new URL("version.js", outDir), out);
console.log(`example version → ${denoJson.version}`);
